"""Generate an idempotent SQL seed, resolving existing UUIDs by unique names."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
catalogue = json.loads((ROOT / "ml/data/careers/catalogue.json").read_text(encoding="utf8"))
# Only public metadata needed by SQL is included; no assessment keys.
payload = {"version": catalogue["version"], "skills": [{k: s[k] for k in ["id", "key", "name", "category", "description"]} for s in catalogue["skills"]], "roles": [{k: r[k] for k in ["id", "name", "description", "requirements"]} for r in catalogue["roles"]] + [catalogue["personal_goal_role"] | {"requirements": []}], "dependencies": catalogue["dependencies"]}
data = json.dumps(payload, separators=(",", ":"), ensure_ascii=False)
assert "$career_data$" not in data
sql = """-- Generated by scripts/seed-career-catalogue.py. Safe to apply repeatedly.
-- Uses names to preserve existing production UUIDs and all referenced progress.
begin;
create temporary table vf_career_seed (data jsonb) on commit drop;
insert into vf_career_seed values ($career_data$""" + data + """$career_data$::jsonb);

insert into public.skills(id,name,category,description)
select (s->>'id')::uuid, s->>'name', s->>'category', s->>'description'
from vf_career_seed, jsonb_array_elements(data->'skills') s
on conflict (name) do update set category=excluded.category, description=excluded.description;

insert into public.roles(id,name,description)
select (r->>'id')::uuid, r->>'name', r->>'description'
from vf_career_seed, jsonb_array_elements(data->'roles') r
on conflict (name) do update set description=excluded.description;

insert into public.role_skills(role_id,skill_id,weight,required_score,essential,catalogue_version)
select actual_role.id, actual_skill.id, (requirement->>'importance')::numeric,
       (requirement->>'target')::numeric, (requirement->>'essential')::boolean, data->>'version'
from vf_career_seed
cross join lateral jsonb_array_elements(data->'roles') role_definition
cross join lateral jsonb_array_elements(role_definition->'requirements') requirement
join public.roles actual_role on actual_role.name=role_definition->>'name'
join lateral (select skill_definition->>'name' as name from jsonb_array_elements(data->'skills') skill_definition where skill_definition->>'key'=requirement->>'skill') configured on true
join public.skills actual_skill on actual_skill.name=configured.name
on conflict (role_id,skill_id) do update set weight=excluded.weight, required_score=excluded.required_score,
  essential=excluded.essential, catalogue_version=excluded.catalogue_version;

insert into public.skill_dependencies(prerequisite_skill_id,dependent_skill_id)
select prerequisite.id, dependent.id
from vf_career_seed
cross join lateral jsonb_array_elements(data->'dependencies') dependency
join lateral (select s->>'name' as name from jsonb_array_elements(data->'skills') s where s->>'key'=dependency->>0) p on true
join lateral (select s->>'name' as name from jsonb_array_elements(data->'skills') s where s->>'key'=dependency->>1) d on true
join public.skills prerequisite on prerequisite.name=p.name
join public.skills dependent on dependent.name=d.name
on conflict do nothing;

commit;
"""
(ROOT / "supabase/migrations/20261106_third_career_cohort.sql").write_text(sql, encoding="utf8")
print(f"Generated additive seed: {len(payload['roles'])-1} careers plus personal-goal storage role; {len(payload['skills'])} skills.")
